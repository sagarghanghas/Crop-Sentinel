export function useI18n() {
  const { language, setLanguage } = useWeatherStore()
  const t = TRANSLATIONS[language] ?? TRANSLATIONS.en
  const keyMap = FORM_AND_FIELD_KEYS[language] ?? FORM_AND_FIELD_KEYS.en

  const tKey = (key: string, fallback?: string): string => {
    return keyMap[key] ?? FORM_AND_FIELD_KEYS.en[key] ?? fallback ?? key
  }

  return { language, setLanguage, t, tKey }
}

export function translateRiskStatus(status: string, lang: AppLanguage): string {
  const s = (status || '').toLowerCase()
  if (lang === 'hi') {
    if (s === 'healthy' || s === 'low') return 'स्वस्थ / कम जोखिम (Healthy)'
    if (s === 'watch' || s === 'moderate' || s === 'warning') return 'निगरानी आवश्यक (Watch)'
    if (s === 'high-risk' || s === 'high' || s === 'critical') return 'उच्च जोखिम (High-Risk)'
  }
  return status.toUpperCase()
}

export function translateGrowthStage(stage: string, lang: AppLanguage): string {
  if (lang !== 'hi') return stage
  const map: Record<string, string> = {
    Seedling: 'अंकुरण / पौध (Seedling)',
    Vegetative: 'वानस्पतिक वृद्धि (Vegetative)',
    Flowering: 'फूल आने की अवस्था (Flowering)',
    'Fruiting/Grain Fill': 'फल / दाना भरने की अवस्था (Grain Fill)',
    Maturity: 'पकने की अवस्था (Maturity)',
  }
  return map[stage] || stage
}
